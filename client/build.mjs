/**
 * dsh-evolution — Client(web) 构建脚本
 *
 * 产物契约（DSH client-modules）：classic `<script>` 加载，factory 是 CJS 闭包，
 * 接收运行时注入的 `require`。
 *
 *   window.__ModuleLoader__.load({
 *     id: "<包名>",
 *     factory: (require) => { ...; return module.exports }
 *   })
 *
 * react / react/jsx-runtime 由运行时 seed 并提供，因此**外部化不打包**。
 *
 * 构建：`node client/build.mjs`
 */
import { execSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'client', 'index.js')
const outDir = join(root, 'client', 'dist')
const outFile = join(outDir, 'index.js')
const tmpFile = join(outDir, '_inner.cjs')

/** 必须与 package.json 的 name 完全一致：运行时按它做模块登记与去重。 */
const PACKAGE_ID = 'dsh-evolution'

/**
 * 版本号单一来源 = package.json。面板代码里只写占位符 __DVEV_VERSION__，
 * 构建时在这里替换成真实版本 —— 发版只改 package.json 一处。
 */
const VERSION = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version
const VERSION_PLACEHOLDER = '__DVEV_VERSION__'

function runEsbuild(args) {
  // stdio: inherit —— esbuild 输出直通终端。刻意不捕获管道：
  // 在某些沙箱/CI 环境下捕获子进程 stdio 会失败，而这个构建脚本对失败原因
  // 的可见性要求很高（构建是发布链路的第一步）。
  try {
    execSync(`npx --yes esbuild ${args.map((a) => JSON.stringify(a)).join(' ')}`, {
      stdio: 'inherit',
      shell: process.platform === 'win32',
    })
  } catch (e) {
    console.error('\n[build] esbuild 失败。请确认能访问 npm registry（首次会下载 esbuild），')
    console.error('[build] 或先在仓库根目录执行 `npm i -D esbuild` 安装本地依赖。')
    throw new Error(`esbuild failed: ${e.message || e}`)
  }
}

mkdirSync(outDir, { recursive: true })

// 1) 转译：JSX → automatic runtime，ESM import → CJS require，不 bundle
runEsbuild([
  src,
  '--format=cjs',
  '--platform=browser',
  '--jsx=automatic',
  '--loader:.js=jsx',
  `--outfile=${tmpFile}`,
  '--log-level=warning',
])

// 2) 包上 ModuleLoader 闭包壳
const banner = `/* dsh-evolution client bundle — generated by client/build.mjs; do not edit */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(PACKAGE_ID)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
`
const footer = `
\t\texports.apply = apply;
\t\texports.inject = inject;
\t\treturn module.exports;
\t}
});
`

const inner = readFileSync(tmpFile, 'utf8')
// 版本号占位符替换：必须恰好命中一次 —— 少了说明面板源码丢了占位符，
// 多了说明有人把字面量写进了别的字符串。两种都按构建失败处理，宁可在
// 发布链路上炸掉，也不让带 "__DVEV_VERSION__" 的面板流到用户手里。
const hits = inner.split(VERSION_PLACEHOLDER).length - 1
if (hits !== 1) {
  throw new Error(`[build] ${VERSION_PLACEHOLDER} 应恰好出现 1 次，实际 ${hits} 次`)
}
const bundled = `${banner}${inner.replaceAll(VERSION_PLACEHOLDER, VERSION)}\n${footer}`
writeFileSync(outFile, bundled, 'utf8')
rmSync(tmpFile, { force: true })

console.log(`[build] ok → ${outFile} (${bundled.length} bytes)`)
